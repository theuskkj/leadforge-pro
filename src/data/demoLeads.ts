import { uid, computePriority } from '../lib/utils'
import type { Lead } from '../types'

const now = new Date().toISOString()

function createLead(input: Omit<Lead, 'id' | 'activities' | 'createdAt' | 'updatedAt' | 'priority'>): Lead {
  return {
    ...input,
    id: uid(),
    priority: computePriority({
      hasWebsite: Boolean(input.website),
      rating: input.rating,
      reviewCount: input.reviewCount,
      hasPhone: Boolean(input.phone),
    }),
    createdAt: now,
    updatedAt: now,
    activities: [{ id: uid(), type: 'created', description: 'Lead importado na base demo', createdAt: now }],
  }
}

